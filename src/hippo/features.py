"""Structured feature data: features/<slug>/feature.json, and the index.md built from it.

Agents never write feature.json by hand. They call `hippo feature set`, which
validates the input against the repo, writes the file, and regenerates index.md.
"""

import argparse
import glob
import json
import re
from dataclasses import asdict, dataclass, field
from pathlib import Path

from hippo import project, ui
from hippo.errors import HippoError
from hippo.fsutil import atomic_write_text

SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
KEYWORDS = (3, 6)
KEY_FILES = (1, 10)
INDEX_NOTE = "<!-- Generated by Hippo from features/*/feature.json. Edits here are overwritten. -->"


@dataclass
class KeyFile:
    path: str
    role: str


@dataclass
class Feature:
    slug: str
    name: str
    summary: str
    keywords: list[str]
    key_files: list[KeyFile] = field(default_factory=list)

    @classmethod
    def from_json(cls, data: dict) -> "Feature":
        return cls(
            slug=data["slug"], name=data["name"], summary=data["summary"],
            keywords=list(data["keywords"]),
            key_files=[KeyFile(k["path"], k["role"]) for k in data.get("key_files", [])],
        )

    def to_json(self) -> str:
        return json.dumps(asdict(self), indent=2, ensure_ascii=False) + "\n"


def feature_file(memory_dir: Path, slug: str) -> Path:
    return memory_dir / "features" / slug / "feature.json"


def load_all(memory_dir: Path) -> tuple[list[Feature], list[str]]:
    """All features sorted by slug, plus a problem line for each unreadable file."""
    features, problems = [], []
    for f in sorted((memory_dir / "features").glob("*/feature.json")):
        try:
            features.append(Feature.from_json(json.loads(f.read_text())))
        except (json.JSONDecodeError, KeyError, TypeError) as e:
            problems.append(f"{f.parent.name}/feature.json is unreadable ({e.__class__.__name__})")
    return features, problems


def validate(feature: Feature, repo: Path) -> list[str]:
    errors = []
    if not SLUG.match(feature.slug):
        errors.append(f"slug '{feature.slug}' must be lowercase kebab-case, e.g. 'user-auth'")
    if not feature.name.strip():
        errors.append("--name is required")
    if not feature.summary.strip():
        errors.append("--summary is required")
    elif "\n" in feature.summary:
        errors.append("--summary must be one sentence on one line")

    lo, hi = KEYWORDS
    if not lo <= len(feature.keywords) <= hi:
        errors.append(f"give {lo}-{hi} --keyword values (got {len(feature.keywords)})")
    if len({k.lower() for k in feature.keywords}) != len(feature.keywords):
        errors.append("--keyword values must be distinct")

    lo, hi = KEY_FILES
    if not lo <= len(feature.key_files) <= hi:
        errors.append(f"give {lo}-{hi} --key-file entries (got {len(feature.key_files)})")
    for kf in feature.key_files:
        errors += _check_key_file(kf, repo)
    return errors


def _check_key_file(kf: KeyFile, repo: Path) -> list[str]:
    p = kf.path
    if p.startswith("/") or ".." in Path(p).parts:
        return [f"key file '{p}' must be relative to the repo root, without '..'"]
    if not kf.role.strip():
        return [f"key file '{p}' needs a one-line role"]
    if glob.has_magic(p):
        if not any(Path(m).is_file() for m in glob.glob(str(repo / p), recursive=True)):
            return [f"key file pattern '{p}' matches no files in the repo"]
    elif not (repo / p).is_file():
        return [f"key file '{p}' does not exist in the repo"]
    return []


def render_index(features: list[Feature]) -> str:
    lines = ["# Features", INDEX_NOTE, ""]
    for f in features:
        lines.append(f"- {f.slug} ({f.name}): {f.summary.rstrip('.')}. "
                     f"Keywords: {', '.join(f.keywords)}. → features/{f.slug}/")
    if not features:
        lines.append("No features yet.")
    return "\n".join(lines) + "\n"


def write_index(memory_dir: Path) -> None:
    features, _ = load_all(memory_dir)
    atomic_write_text(memory_dir / "index.md", render_index(features))


# --- `hippo feature set` ------------------------------------------------------

def run_set(args: argparse.Namespace) -> int:
    p = project.resolve(Path.cwd())
    feature = Feature(
        slug=args.slug, name=args.name or "", summary=(args.summary or "").strip(),
        keywords=[k.strip() for k in args.keyword or [] if k.strip()],
        key_files=[KeyFile(path.strip(), role.strip()) for path, role in args.key_file or []],
    )
    errors = validate(feature, p.repo)
    if errors:
        raise HippoError(
            f"feature '{args.slug}' was not saved:\n" + "\n".join(f"  - {e}" for e in errors),
            next_steps=["Fix the values above and run the same `hippo feature set` again."],
        )
    target = feature_file(p.dir, feature.slug)
    existed = target.exists()
    atomic_write_text(target, feature.to_json())
    write_index(p.dir)
    ui.say("updated" if existed else "created",
           f"features/{feature.slug}/feature.json ({len(feature.key_files)} key files); index.md rebuilt")
    return 0


def add_parser(sub) -> None:
    p = sub.add_parser("feature", help="manage structured feature data (used by agents)")
    fsub = p.add_subparsers(dest="feature_command", required=True, metavar="<action>")
    s = fsub.add_parser("set", help="create or replace a feature's feature.json")
    s.add_argument("slug")
    s.add_argument("--name", help="display name, e.g. 'Auth'")
    s.add_argument("--summary", help="one sentence on what it does for users")
    s.add_argument("--keyword", action="append", metavar="WORD", help="repeat 3-6 times")
    s.add_argument("--key-file", action="append", nargs=2, metavar=("PATH", "ROLE"),
                   help="repeat 1-10 times; PATH relative to the repo root, glob allowed")
    s.set_defaults(func=run_set)
