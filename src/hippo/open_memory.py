"""`hippo open`: show the current repo's memory.

  hippo open                             summary: features with keywords, patches, review items
  hippo open --feature auth              one feature: summary, key files, overview, technical
  hippo open --feature auth --decisions  that feature's decisions (hidden unless asked)
  hippo open --review                    items that need your judgment (needs-review.json)
  hippo open --path                      bare path, for scripts: cd "$(hippo open --path)"
  hippo open --finder                    also reveal the folder in Finder
"""

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from hippo import project, ui
from hippo.errors import HippoError
from hippo.features import Feature
from hippo.memory import Memory
from hippo.patches import known_slugs

LABEL = 19  # width of the left column in summary rows


def run(args: argparse.Namespace) -> int:
    if args.decisions and not args.feature:
        raise HippoError("--decisions needs a feature: hippo open --feature <name> --decisions")
    p = project.current(Path.cwd())
    mem = Memory(p.dir)
    if args.path:
        print(p.dir)
    elif args.review:
        _review(mem)
    elif args.feature:
        feature = _find(mem, args.feature)
        (_decisions if args.decisions else _feature)(p, mem, feature)
    else:
        _summary(p, mem)
    if args.finder:
        reveal(p.dir / "features" / args.feature if args.feature else p.dir)
    return 0


def _summary(p: project.Project, mem: Memory) -> None:
    meta = p.meta()
    print(f"Hippo memory · {p.repo.name} ({ui.tilde(p.repo)})")
    print(f"{ui.tilde(p.dir)}/\n")

    features, problems = mem.features()
    pending = sorted(known_slugs(mem)[1])
    if not features:
        print("Features           none yet (the init agent generates them)")
    else:
        width = max(len(s) for s in [f.slug for f in features] + pending) + 3
        print(f"Features ({len(features)})")
        for f in features:
            print(f"  {f.slug:<{width}}{', '.join(f.keywords)}")
    for slug in pending:
        print(f"  {slug:<{width if features else len(slug) + 3}}(new, added at the next consolidation)")
    for line in problems:
        print(f"  ! {line}")
    print()

    patches = mem.patches()
    latest = ""
    if patches:
        last = patches[-1]
        feats = f" ({', '.join(last.features)})" if last.features else ""
        latest = f"   latest {_when(last.created_at)}{feats}"
    _row("Unmerged patches", f"{len(patches)}{latest}")
    review = mem.needs_review()
    _row("Needs review", f"{len(review)} item{'' if len(review) == 1 else 's'}"
         + ("   hippo open --review" if review else ""))
    consolidated = meta.get("last_consolidated_at")
    _row("Last consolidated",
         f"{_when(consolidated) if consolidated else 'never'} · linked {_when(meta['created_at'])}")
    if features:
        ui.next_steps(["Run `hippo open --feature <name>` to see one feature's details."])


def _review(mem: Memory) -> None:
    items = mem.needs_review()
    print(f"Needs review ({len(items)} open)")
    if not items:
        print("\nNothing to review. Items appear here when `hippo sync` finds code no feature "
              "covers, key files that are gone, or questions only you can answer.")
        return
    for i in items:
        print(f"\n  {i['id']}  {i.get('created', '')}  {i['detail']}")
        files = i.get("files") or []
        if files:
            shown = ", ".join(files[:5]) + (f" and {len(files) - 5} more" if len(files) > 5 else "")
            print(f"         {shown}")
        if i.get("commits"):
            print(f"         commits: {', '.join(i['commits'][:5])}")
    ui.next_steps(["To cover unclaimed files, say which feature they belong to (or that they are a "
                   "new feature) in a Claude session; once a feature lists them, the item closes "
                   "at the next sync.",
                   "Or dismiss an item: hippo review done <id>"])


def _find(mem: Memory, slug: str) -> Feature:
    features = {f.slug: f for f in mem.features()[0]}
    if slug in features:
        return features[slug]
    close = difflib.get_close_matches(slug, features, n=1)
    steps = [f"Did you mean:  hippo open --feature {close[0]}"] if close else []
    steps.append("Run `hippo open` to list features." if features
                 else "Features are generated by the init agent; none exist yet.")
    raise HippoError(f"no feature named '{slug}'", next_steps=steps)


def _feature(p: project.Project, mem: Memory, f: Feature) -> None:
    print(f"{f.slug} · {f.name}")
    print(f.summary)
    print(f"Keywords: {', '.join(f.keywords)}")
    print(f"{ui.tilde(p.dir / 'features' / f.slug)}/")

    if f.key_files:
        width = max(len(k.path) for k in f.key_files) + 3
        _section("Key files", "\n".join(f"{k.path:<{width}}{k.role}" for k in f.key_files))
    _section("Overview", _body(mem.doc(f.slug, "overview.md")))
    _section("Technical", _body(mem.doc(f.slug, "technical.md")))

    related = [x for x in mem.patches() if f.slug in x.features]
    if related:
        _section("Unmerged patches", "\n".join(
            f"{_when(x.created_at)}  {x.path.name}" for x in related))
    decisions = mem.decisions(f.slug)
    if decisions:
        ui.next_steps([f"Run `hippo open --feature {f.slug} --decisions` "
                       f"to see its {len(decisions)} recorded decision(s)."])


def _decisions(p: project.Project, mem: Memory, f: Feature) -> None:
    decisions = mem.decisions(f.slug)
    active = sum(d.get("status") == "active" for d in decisions)
    print(f"{f.slug} · decisions ({active} active, {len(decisions) - active} superseded)")
    if not decisions:
        print("\nNo decisions recorded yet. They come from patch notes, "
              "only when you agreed to them in a session.")
    for d in decisions:
        status = d.get("status", "active")
        if d.get("superseded_by"):
            status += f" by {d['superseded_by']}"
        lines = [d.get("decision", "")]
        if d.get("why"):
            lines.append(f"Why: {d['why']}")
        for r in d.get("rejected", []):
            lines.append(f"Rejected: {r}")
        if d.get("also_affects"):
            lines.append(f"Also affects: {', '.join(d['also_affects'])}")
        if d.get("source"):
            lines.append(f"Source: {d['source']}")
        _section(f"{d.get('id', '?')} · {d.get('date', '')} · {status}", "\n".join(lines))


def _body(text: str) -> str:
    """Drop the file's own `# Title` line; the view already shows the name."""
    lines = text.strip().splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    return "\n".join(lines).strip()


def _section(title: str, body: str | None) -> None:
    if not body:
        return
    print(f"\n{title}")
    for line in body.splitlines():
        print(f"  {line}" if line.strip() else "")


def _row(label: str, value: str) -> None:
    print(f"{label:<{LABEL}}{value}")


def _when(iso: str) -> str:
    """2026-10-03T14:30:12 -> 2026-10-03 14:30; filename stamps 2026-10-03T143012 too."""
    date, _, time = iso.partition("T")
    time = time.replace(":", "")
    return f"{date} {time[:2]}:{time[2:4]}" if len(time) >= 4 else date


def reveal(path: Path) -> None:
    opener = "open" if sys.platform == "darwin" else "xdg-open"
    subprocess.run([opener, str(path)], stdin=subprocess.DEVNULL, check=False)
